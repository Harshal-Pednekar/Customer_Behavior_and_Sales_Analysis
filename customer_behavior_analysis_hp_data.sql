--Q6. Do subscribed customers spend more? Compare average spend and total revenue between subscribers and non-subscribers.
select subscription_status,
COUNT(customer_id) as "Total customers",
ROUND(AVG(purchase_amount_inr)/ 1000.0, 2) || 'K' as "Avg Spend",
Round(SUM(purchase_amount_inr) / 1000000.0, 2) || 'M' as "Total Revenue"
from customer_data
group by subscription_status
order by "Total Revenue", "Avg Spend" desc;

--Q7. What is the total revenue generated by male vs. female customers?
select gender, ROUND(SUM(purchase_amount_inr) / 1000000.0, 2) || 'M' as "Revenue (INR)"
from customer_data
group by gender

--Q8. Segment customers into New, Returning, and Loyal based on their total number of previous purchases, 
--and show the count of each segment.
with customer_type as(
select customer_id, previous_purchases,
CASE 
	WHEN previous_purchases = 1 THEN 'New'
	WHEN previous_purchases BETWEEN 2 AND 10 THEN 'Returning'
	ELSE 'Loyal'
	END AS customer_segment
from customer_data
)

select customer_segment, count(*) as "Number of Customers"
from customer_type
group by customer_segment
order by "Number of Customers" desc

--Q9. What is the distribution of customers across different purchase frequency groups?
SELECT
    frequency_of_purchases,
    COUNT(customer_id) AS total_customers,
    ROUND(
        COUNT(customer_id) * 100.0 /
        (SELECT COUNT(*) FROM customer_data),
        2
    ) || '%' AS percentage
FROM customer_data
GROUP BY frequency_of_purchases
ORDER BY COUNT(customer_id) DESC;

--Q10. What is the revenue contribution of each age group?
select age_group,
ROUND(SUM(purchase_amount_inr)/ 1000000.0, 2) || 'M' as total_revenue
from customer_data
group by age_group
order by total_revenue desc;

