--Q1. Which Locations Generate the Highest Revenue?
SELECT
    location,
    ROUND(SUM(purchase_amount_inr) / 1000000.0, 2) || ' M' AS total_revenue,
    COUNT(customer_id) AS total_customers,
    ROUND(AVG(purchase_amount_inr),2) AS avg_purchase
FROM customer_data
GROUP BY location
ORDER BY SUM(purchase_amount_inr) DESC;

--Q2. Which Product Categories Generate the Highest Revenue?
SELECT
    category,
    ROUND(SUM(purchase_amount_inr) / 1000000.0,2) || ' M' AS total_revenue,
    COUNT(customer_id) AS total_orders,
    ROUND(AVG(review_rating::numeric),2) AS avg_rating
FROM customer_data
GROUP BY category
ORDER BY SUM(purchase_amount_inr) DESC;

--Q3. Which are the top 5 products with the highest average review rating?
select item_purchased as products, ROUND(AVG(review_rating::numeric), 2) as "Average Product Rating"
from customer_data
group by item_purchased
order by AVG(review_rating) desc
limit 5;

--Q4. Which Payment Method Generates the Highest Revenue and Average Purchase Amount?
SELECT
    payment_method,
    ROUND(SUM(purchase_amount_inr) / 1000000.0, 2) || ' M' AS total_revenue,
    ROUND(AVG(purchase_amount_inr) / 1000.0, 2) || 'K' AS avg_purchase_amount,
    COUNT(customer_id) AS total_orders
FROM customer_data
GROUP BY payment_method
ORDER BY SUM(purchase_amount_inr) DESC;

--Q5. Which Season Generates the Highest Revenue?
SELECT
    season,
    ROUND(SUM(purchase_amount_inr) / 1000000.0, 2) || ' M' AS total_revenue
FROM customer_data
GROUP BY season
ORDER BY SUM(purchase_amount_inr) DESC;
